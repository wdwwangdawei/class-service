const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('electronAPI', {
  loadTables: () => ipcRenderer.invoke('load-tables'),
  getTable: (id) => ipcRenderer.invoke('get-table', id),
  createTable: (params) => ipcRenderer.invoke('create-table', params),
  addTable: (table) => ipcRenderer.invoke('add-table', table),
  updateTable: (table) => ipcRenderer.invoke('update-table', table),
  deleteTable: (id) => ipcRenderer.invoke('delete-table', id),
  getWeekLabels: () => ipcRenderer.invoke('get-week-labels'),
  printTable: (table) => ipcRenderer.invoke('print-table', table),
  confirmBox: (options) => ipcRenderer.invoke('confirm-box', options),
  getConfig: () => ipcRenderer.invoke('get-config'),
  verifyPassword: (input) => ipcRenderer.invoke('verify-password', input),
  changePassword: (params) => ipcRenderer.invoke('change-password', params),
  togglePassword: (params) => ipcRenderer.invoke('toggle-password', params),
  toggleUninstallPassword: (params) => ipcRenderer.invoke('toggle-uninstall-password', params),
  getAppVersion: () => ipcRenderer.invoke('get-app-version'),
  backupExport: () => ipcRenderer.invoke('backup-export'),
  backupImport: () => ipcRenderer.invoke('backup-import'),
  exportExcel: (table) => ipcRenderer.invoke('export-excel', table),
  importExcel: (params) => ipcRenderer.invoke('import-excel', params),
  importNames: () => ipcRenderer.invoke('import-names'),
  applyNamesToTable: (params) => ipcRenderer.invoke('apply-names-to-table', params),
  importScores: (params) => ipcRenderer.invoke('import-scores', params),
  addRow: (tableId) => ipcRenderer.invoke('add-row', tableId),
  removeRow: (tableId) => ipcRenderer.invoke('remove-row', tableId),
  getChangelog: () => ipcRenderer.invoke('get-changelog'),
  verifySuperPassword: (input) => ipcRenderer.invoke('verify-super-password', input),
  verifyCreator: (d) => ipcRenderer.invoke('verify-creator', d),
  addLog: (d) => ipcRenderer.invoke('add-log', d),
  getLogs: () => ipcRenderer.invoke('get-logs'),
  updateSettingsConfig: (params) => ipcRenderer.invoke('update-settings-config', params),
  listAutoBackups: () => ipcRenderer.invoke('list-auto-backups'),
  restoreAutoBackup: (fileName) => ipcRenderer.invoke('restore-auto-backup', fileName),
  checkUpdate: () => ipcRenderer.invoke('check-update'),
  downloadUpdate: (url) => ipcRenderer.invoke('download-update', url),
  installUpdate: (tmpPath) => ipcRenderer.invoke('install-update', tmpPath),
  onUpdateAvailable: (cb) => ipcRenderer.on('update-available', (e, data) => cb(data)),
  onUpdateDownloadProgress: (cb) => ipcRenderer.on('update-download-progress', (e, data) => cb(data)),
  syncSetPassword: (pwd) => ipcRenderer.invoke('sync-set-password', pwd),
  syncSetToken: (token) => ipcRenderer.invoke('sync-set-token', token),
  syncGetToken: () => ipcRenderer.invoke('sync-get-token'),
  syncUpload: (pwd) => ipcRenderer.invoke('sync-upload', pwd),
  syncDownload: (pwd) => ipcRenderer.invoke('sync-download', pwd),
  syncGetStatus: () => ipcRenderer.invoke('sync-get-status'),
  rankGet: () => ipcRenderer.invoke('rank-get'),
  rankSave: (rank) => ipcRenderer.invoke('rank-save', rank),
  rankReset: () => ipcRenderer.invoke('rank-reset')
});



